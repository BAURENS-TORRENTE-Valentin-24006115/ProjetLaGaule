package fr.iut.laGaule.model.Consumables.Potions;

/**
 * Enum representing the various effects that magic potions can have.
 * These effects modify character abilities or states when potions are consumed.
 */
public enum Effects {
    /** Increases the character's strength */
    STRENGTH,
    /** Makes the character invincible */
    INVINCIBILITY,
    /** Creates a clone of the character */
    CLONE,
    /** Transforms the character into another form */
    METAMORPHOSIS,
    /** Fully satisfies the character's hunger */
    SATURATION,
    /** Causes instant death to the character */
    DEATH
}
